from __future__ import annotations

import logging
import os
import re
import shlex
import shutil
import subprocess
from pathlib import Path
from typing import Literal

from free_games_notifier.config import DATA_DIR, DIST_NAME
from free_games_notifier.model import GameOffer

logger = logging.getLogger(__name__)

JOB_ID_FILE = DATA_DIR / "termux_schedular_job_id.txt"
MIN_PERIOD_MIN = 15  # Android JobScheduler minimum is 15 minutes
MIN_PERIOD_MS = MIN_PERIOD_MIN * 60 * 1000

TERMUX_API_HELP_TEXT = (
    "Ensure the termux-api package is installed ('pkg install termux-api') "
    "and the Termux:API companion app is installed."
)


def is_termux_environment() -> bool:
    return bool(
        os.environ.get("TERMUX_VERSION", "").strip()
        or "com.termux" in os.environ.get("PREFIX", "")
    )


def is_termux_api_available() -> bool:
    return bool(
        # Is set if Termux:API app is installed, at least on Termux 0.118 and Termux:API 0.53
        os.environ.get("TERMUX_API_VERSION", "").strip()
        # Check for termux-api package based on:
        # https://github.com/termux/termux-api-package/blob/9e7f1531e1aa4a9c1e261a2dbde4de93653c366e/scripts/termux-battery-status.in#L22
        and (Path(os.environ.get("PREFIX", "")) / "libexec" / "termux-api").is_file()
    )


def send_termux_notification(game_offer: GameOffer) -> bool:
    if not shutil.which("termux-notification"):
        logger.error(f"'termux-notification' command not found. {TERMUX_API_HELP_TEXT}")
        return False

    title = f"{game_offer.title!r} is available for Free"
    content = f"The offer ends on {game_offer.offer_end_fmt}."
    if game_offer.description.strip():
        content += f"\n\n{game_offer.description.strip()}"

    open_action = f"termux-open-url {shlex.quote(game_offer.url)}"

    cmd = [
        "termux-notification",
        "--title",
        title,
        "--content",
        content,
        "--action",
        open_action,
        "--button1",
        "Open Store",
        "--button1-action",
        open_action,
        "--priority",
        "high",
    ]

    try:
        logger.debug(f"Executing termux-notification: {cmd}")
        res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        if res.returncode != 0:
            logger.error(
                f"termux-notification failed with exit code {res.returncode}: {res.stderr.strip()}"
            )
            return False
        return True
    except (subprocess.SubprocessError, OSError) as e:
        logger.error("Failed to execute termux-notification: %s", e)
        return False


def parse_interval_to_ms(interval: str | int) -> int:
    """
    Parse a human-readable interval (e.g. '1d', '12h', '30m') into milliseconds.
    """
    if isinstance(interval, int):
        ms = interval
    else:
        match = re.match(r"^(\d+)\s*([mhdws]?)$", interval.strip().lower())
        if not match:
            raise ValueError(
                f"Invalid interval format: {interval!r}. Use e.g. '1d', '12h', '30m'."
            )
        val, unit = match.groups()
        num = int(val)
        match unit:
            case "m":
                ms = num * 60 * 1000
            case "h":
                ms = num * 60 * 60 * 1000
            case "d":
                ms = num * 24 * 60 * 60 * 1000
            case "w":
                ms = num * 7 * 24 * 60 * 60 * 1000
            case "s":
                ms = num * 1000
            case "":
                # If unit is omitted, allow raw milliseconds if >= MIN_PERIOD_MS
                if num >= MIN_PERIOD_MS:
                    ms = num
                else:
                    raise ValueError(
                        f"Ambiguous interval number: {interval!r}. Please specify a unit (e.g. '{num}m', '{num}h', '{num}d')."
                    )
            case _:
                raise ValueError(f"Unknown interval unit: {unit!r}")

    if ms < MIN_PERIOD_MS:
        raise ValueError(
            f"Interval {interval!r} ({ms}ms) is less than the Android JobScheduler minimum "
            f"of {MIN_PERIOD_MIN} minutes ({MIN_PERIOD_MS}ms)."
        )

    return ms


def generate_job_script(
    script_path: Path,
    workdir: Path,
    executable: str,
    args: list[str] | None = None,
    log_file: Path | None = None,
) -> Path:
    args_str = f" {' '.join(shlex.quote(a) for a in args)}" if args else ""
    run_cmd = f"{executable}{args_str}"

    script_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "#!/bin/sh",
        f"# Auto-generated by {DIST_NAME} schedule",
        "set -e",
        "",
        f'cd "{workdir.resolve()}" || exit 1',
    ]

    if log_file:
        resolved_log_file = log_file.resolve()
        lines.extend(
            [
                f'mkdir -p "{log_file.parent.resolve()}"',
                f'if [ -f "{resolved_log_file}" ]; then',
                f'    if [ "$(wc -l < "{resolved_log_file}" 2>/dev/null || echo 0)" -ge 1000 ]; then',
                f'        tail -n 500 "{resolved_log_file}" > "{resolved_log_file}.tmp" && mv "{resolved_log_file}.tmp" "{resolved_log_file}"',
                "    fi",
                "fi",
                f'exec >> "{resolved_log_file}" 2>&1',
                f"echo \"[$(date '+%Y-%m-%d %H:%M:%S')] Running {DIST_NAME}...\"",
            ]
        )

    lines.append(f'exec {run_cmd} "$@"')
    lines.append("")

    script_content = "\n".join(lines)
    script_path.write_text(script_content, encoding="utf-8")
    script_path.chmod(0o755)

    return script_path


def get_stored_job_id() -> int | None:
    if JOB_ID_FILE.is_file():
        try:
            return int(JOB_ID_FILE.read_text(encoding="utf-8").strip())
        except (ValueError, OSError):
            return None
    return None


def store_job_id(job_id: int) -> None:
    JOB_ID_FILE.parent.mkdir(parents=True, exist_ok=True)
    JOB_ID_FILE.write_text(str(job_id), encoding="utf-8")


def clear_stored_job_id() -> None:
    try:
        if JOB_ID_FILE.is_file():
            JOB_ID_FILE.unlink()
    except OSError:
        pass


def schedule_termux_job(
    script_path: Path,
    job_id: int | None = None,
    period_ms: int = MIN_PERIOD_MS,
    network: Literal["any", "unmetered", "cellular", "not_roaming", "none"] = "any",
    battery_not_low: bool = True,
    storage_not_low: bool = False,
    charging: bool = False,
    persisted: bool = True,
) -> int:
    if not shutil.which("termux-job-scheduler"):
        raise RuntimeError(
            f"'termux-job-scheduler' command not found. {TERMUX_API_HELP_TEXT}"
        )

    cmd = [
        "termux-job-scheduler",
        "-s",
        str(script_path.resolve()),
        "--period-ms",
        str(period_ms),
        "--network",
        network,
        "--battery-not-low",
        str(battery_not_low).lower(),
        "--charging",
        str(charging).lower(),
        "--storage-not-low",
        str(storage_not_low).lower(),
        "--persisted",
        str(persisted).lower(),
    ]

    existing_id = get_stored_job_id()
    if job_id is None:
        job_id = existing_id
    if existing_id is not None and job_id != existing_id:
        try:
            cancel_termux_job(existing_id)
        except (RuntimeError, subprocess.SubprocessError, OSError) as e:
            logger.debug(f"Failed to cancel existing job {existing_id}: {e}")

    if job_id is not None:
        cmd.extend(["--job-id", str(job_id)])

    res = subprocess.run(cmd, capture_output=True, text=True, check=True)

    match = re.search(r"scheduling job (\d+):", res.stdout, re.IGNORECASE)
    assert match, "Failed to retrieve ID for scheduled job"

    assigned_id = int(match.group(1))
    store_job_id(assigned_id)

    return assigned_id


def cancel_termux_job(
    job_id: int | None = None, cancel_all: bool = False
) -> subprocess.CompletedProcess[str]:
    if not shutil.which("termux-job-scheduler"):
        raise RuntimeError(
            f"'termux-job-scheduler' command not found. {TERMUX_API_HELP_TEXT}"
        )

    if cancel_all:
        cmd = ["termux-job-scheduler", "--cancel-all"]
        res = subprocess.run(cmd, capture_output=True, text=True, check=True)
        clear_stored_job_id()
        return res

    existing_id = get_stored_job_id()
    target_id = job_id if job_id is not None else existing_id
    if target_id is None:
        raise RuntimeError("No scheduled job to cancel.")

    cmd = ["termux-job-scheduler", "--cancel", "--job-id", str(target_id)]
    res = subprocess.run(cmd, capture_output=True, text=True, check=True)
    if target_id == existing_id:
        clear_stored_job_id()

    return res


def get_pending_termux_jobs() -> str:
    if not shutil.which("termux-job-scheduler"):
        raise RuntimeError(
            f"'termux-job-scheduler' command not found. {TERMUX_API_HELP_TEXT}"
        )

    res = subprocess.run(
        ["termux-job-scheduler", "--pending"],
        capture_output=True,
        text=True,
        check=True,
    )
    return res.stdout
